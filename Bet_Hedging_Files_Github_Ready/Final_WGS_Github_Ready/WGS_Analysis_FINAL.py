def draw_thermal_trajectory(ax, regime, days, values, linestyle="solid", halo=False,
                            fill_by_phase=False, marker_override=None,
                            continuous_dash=False,
                            colour_day0_by_regime=False):
    """Draw one condition's trajectory with the 96-well plate styling:
    the line is split into daily segments coloured red on hot days and blue
    on cold days; markers sit at the actual timepoints, coloured by the
    phase that sample experienced before harvest. Day 0 is drawn grey,
    since it is the shared starting point before any regime applies."""
    days = np.asarray(days, dtype=float)
    values = np.asarray(values, dtype=float)
    good = ~np.isnan(values)
    days, values = days[good], values[good]
    if len(days) < 1:
        return
    if len(days) >= 2:
        fine = np.arange(days.min(), days.max() + 1)
        interp = np.interp(fine, days, values)
        segments, colors = [], []
        for i in range(len(fine) - 1):
            segments.append([(fine[i], interp[i]), (fine[i + 1], interp[i + 1])])
            # The state belongs to the interval beginning at fine[i].  Using
            # the right-hand endpoint shifts every hot block one day early and
            # incorrectly makes the initial day 0-to-1 interval cold.
            colors.append(state_color(daily_thermal_state(regime, int(fine[i]))))
        if halo:
            ax.add_collection(LineCollection(segments, colors=[HALO_COLOR] * len(segments),
                                             linewidths=HALO_WIDTH, linestyles="solid",
                                             zorder=1.8, capstyle="round"))
        base_linestyle = "solid" if continuous_dash else linestyle
        ax.add_collection(LineCollection(segments, colors=colors, linewidths=2.5,
                                         linestyles=base_linestyle, zorder=2))
        if continuous_dash:
            # The thermal line is assembled from one-day coloured segments.
            # Applying a dash pattern to each segment separately restarts the
            # pattern every day and can make parts of the line look solid. A
            # continuous white mask creates one uninterrupted dashed trajectory
            # while retaining the red and blue thermal colours underneath.
            ax.plot(fine, interp, color="white", linewidth=2.8,
                    linestyle=(0, (4, 6)), zorder=2.2,
                    solid_capstyle="butt", dash_capstyle="butt")
    marker = marker_override or REGIME_MARKERS[regime]
    for d, v in zip(days, values):
        if d == 0 and colour_day0_by_regime:
            phase = daily_thermal_state(regime, 0)
        else:
            phase = harvest_phase(regime, int(d))
        col = state_color(phase)
        # Filled = hot-phase harvest, open = cold-phase. The claim is that every
        # hot harvest sits above every cold one, and fill makes that legible
        # without the reader going to the table.
        if fill_by_phase and phase == "C":
            ax.plot(d, v, marker=marker, color=col,
                    markerfacecolor="white", markeredgecolor=col,
                    markeredgewidth=1.6, markersize=8, zorder=3)
        else:
            ax.plot(d, v, marker=marker, color=col,
                    markersize=8, markeredgecolor="white", markeredgewidth=0.8,
                    zorder=3)


