def _phase_groups(measurements):
    """Hot-phase harvests first, then cold, each ordered by condition then day."""
    def sort_key(r):
        return (REGIME_ORDER.index(r["regime"]), r["day"])
    hot = sorted([r for r in measurements if r["phase"] == "H"], key=sort_key)
    cold = sorted([r for r in measurements if r["phase"] == "C"], key=sort_key)
    return hot, cold


