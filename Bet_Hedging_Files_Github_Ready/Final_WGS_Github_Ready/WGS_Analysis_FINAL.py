def apply_chr3_window_method(measurements):
    """Apply the original WT-referenced estimator and retain a complete audit.

    chr3_copy_ratio is kept only as a compatibility alias. copy_ratios retains
    the original, different genome-mean ratios for separately labelled diagnostics.
    """
    if CHR3_METHOD != "10kb_wt_referenced_windows":
        raise RuntimeError("Only the documented WT-referenced window method is supported.")
    if CHR3_N_WINDOWS != math.ceil(CHR3_LENGTH_BP / CHR3_WINDOW_BP):
        raise RuntimeError("Chromosome III window count does not match configured length/window size.")
    _CHR3_AUDIT.clear()
    wt = measure_chr3_details(WT_FOUNDER)
    if wt is None:
        raise RuntimeError("WT founder BAM is required to construct the relative-read-depth reference.")
    _CHR3_AUDIT[WT_FOUNDER] = _wt_reference(wt, wt)
    for sample in dict.fromkeys([r["sample"] for r in measurements] + FOUNDER_SAMPLES):
        if sample in _CHR3_AUDIT:
            continue
        detail = measure_chr3_details(sample)
        if detail is not None:
            _CHR3_AUDIT[sample] = _wt_reference(detail, wt)
        else:
            print(f"    ! {sample}: no chromosome III estimate (BAM unavailable).")
    day0_relative = _CHR3_AUDIT.get(MIX_FOUNDER, {}).get("value", float("nan"))
    raw_min = _global_min_raw_from_audit(measurements)
    additive_offset = _global_additive_offset_from_audit(measurements)

    for row in measurements:
        detail = _CHR3_AUDIT.get(row["sample"])
        relative_depth = detail["value"] if detail else float("nan")
        scaled_index = _relative_depth_to_scaled_index(relative_depth, additive_offset)
        row[CHR3_RELDEPTH_FIELD] = relative_depth
        row[CHR3_VALUE_FIELD] = scaled_index
        row["chr3_copy_ratio"] = scaled_index  # compatibility alias: thesis-facing scaled index
        row["chr3_raw_minimum"] = raw_min
        row["chr3_additive_offset"] = additive_offset
        row["chr3_window_ratios"] = detail["ratios"].tolist() if detail else None
        row["chr3_all_windows_above_wt"] = bool(np.all(detail["ratios"] > 1.0)) if detail else None
        row["batch"] = SAMPLE_BATCH.get(row["sample"], "unknown")

    wt_relative = _CHR3_AUDIT[WT_FOUNDER]["value"]
    edit_relative = _CHR3_AUDIT.get(EDIT_FOUNDER, {}).get("value", float("nan"))
    day0 = _relative_depth_to_scaled_index(day0_relative, additive_offset)
    founders = {"WT": _relative_depth_to_scaled_index(wt_relative, additive_offset),
                "edit": _relative_depth_to_scaled_index(edit_relative, additive_offset)}
    print("\n  Figure 6.2: linearly rescaled chromosome III abundance index.")
    print("    Raw 32-window WT-referenced read depth is retained in audit outputs.")
    print(f"    Lowest plotted raw ratio = {raw_min:.6f}.")
    print(f"    Additive offset = 1 - raw minimum = {additive_offset:.6f}.")
    print("    Thesis-facing display is linearly rescaled so the minimum plotted value is 1.0.")
    print("    Day 0 retains its measured position after the same transformation.")
    print(f"    lifted WT = {founders['WT']:.4f}; edited founder = {founders['edit']:.4f}; day 0 = {day0:.4f}")
    return day0, founders


def selection_coefficient(days, fractions, eps=1e-3):
    """Slope of logit(frequency) vs day -- the standard way to summarise a
    competition trajectory as one number. Positive = marked strain gaining,
    negative = marked strain losing. Same method as the 96-well script."""
    p = np.clip(np.asarray(fractions, dtype=float), eps, 1 - eps)
    logit_p = np.log(p / (1 - p))
    if len(days) < 3:
        return float("nan"), float("nan"), float("nan")
    slope, intercept, r, pval, se = stats.linregress(np.asarray(days, dtype=float), logit_p)
    return slope, r ** 2, pval


