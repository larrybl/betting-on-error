_MEASURE_CACHE = {}


def measure_one(bam_sample):
    """Original marker balance and genome-mean depth ratios for one sample.
    These per-chromosome ratios are retained as legacy diagnostics, not somy.
    """
    if bam_sample in _MEASURE_CACHE:
        return _MEASURE_CACHE[bam_sample]
    depths = run_samtools_coverage(f"{BAM_DIR}/{bam_sample}{BAM_SUFFIX}")
    if depths is None:
        _MEASURE_CACHE[bam_sample] = None
        return None
    baseline = [depths[c] for c in GENOME_BASELINE_CONTIGS if c in depths]
    genome_mean = (sum(baseline) / len(baseline)) if baseline else 0.0
    kanmx = depths.get(KANMX_CONTIG_NAME, 0.0)
    ho = depths.get(HO_INTACT_CONTIG_NAME, 0.0)
    total = kanmx + ho
    marked = (kanmx / total) if total > 0 else float("nan")
    copy_ratios = {label: (depths.get(contig, 0.0) / genome_mean if genome_mean > 0 else float("nan"))
                   for contig, label in ALL_CHROM_CONTIGS.items()}
    out = {"genome_mean_depth": genome_mean, "marked_fraction": marked,
           "copy_ratios": copy_ratios}
    _MEASURE_CACHE[bam_sample] = out
    return out


def measure_samples():
    """Estimate edited/WT balance and retain legacy chromosome-depth diagnostics.

    Raw KanMX/(KanMX + intact-HO) read fractions are first calibrated against the
    confirmed 50:50 day-0 mixture.  This corrects systematic differences in read
    recovery between the two marker sequences.  The calibrated marked-cell
    fraction is then converted to edited-cell fraction according to marker
    orientation in each competition.
    """
    day0_measurement = measure_one(MIX_FOUNDER)
    if day0_measurement is None:
        raise RuntimeError(
            "The confirmed day-0 mixture BAM is required to calibrate marker-read fractions."
        )
    day0_marker_read_fraction = day0_measurement["marked_fraction"]
    odds_multiplier = marker_odds_calibration_multiplier(day0_marker_read_fraction)

    rows = []
    for sample in SAMPLES:
        m = measure_one(sample)
        if m is None:
            continue
        regime, day = SAMPLE_INFO[sample]
        raw_marker_fraction = m["marked_fraction"]
        calibrated_marked = calibrate_marked_fraction(raw_marker_fraction, odds_multiplier)
        edited = edited_fraction(regime, calibrated_marked)
        rows.append({
            "sample": sample, "regime": regime, "day": day,
            "phase": harvest_phase(regime, day),
            "genome_mean_depth": m["genome_mean_depth"],
            "marker_read_fraction": raw_marker_fraction,
            "marked_fraction": calibrated_marked,
            "marker_odds_calibration_multiplier": odds_multiplier,
            "edited_fraction": edited,
            "wt_fraction": 1.0 - edited if edited == edited else float("nan"),
            "chr3_copy_ratio": m["copy_ratios"].get("chrIII", float("nan")),
            "copy_ratios": m["copy_ratios"],
        })
    rows.sort(key=lambda r: (REGIME_ORDER.index(r["regime"]), r["day"]))
    return rows


_CHR3_WINDOW_CACHE = {}

def _samtools_depth_chr3_windows(bam_path):
    """Return 32 mean-depth values spanning chromosome III in consecutive 10 kb windows.

    Uses samtools depth with the same MAPQ/flag filters as the rest of the WGS
    pipeline. The final window contains bases 310001-316620.
    """
    if bam_path in _CHR3_WINDOW_CACHE:
        return list(_CHR3_WINDOW_CACHE[bam_path])
    cmd = [
        "samtools", "depth", "-aa", "-Q", str(MIN_MAPQ), "-G", EXCLUDE_FLAGS_HEX,
        "-r", CHR3_CONTIG_NAME, bam_path,
    ]
    try:
        result = subprocess.run(cmd, capture_output=True, text=True, check=True)
    except FileNotFoundError:
        sys.exit("ERROR: samtools not found on PATH.")
    except subprocess.CalledProcessError as e:
        sys.exit(f"ERROR running samtools depth for chromosome III:\n{e.stderr or ''}")

    sums = np.zeros(CHR3_N_WINDOWS, dtype=float)
    counts = np.zeros(CHR3_N_WINDOWS, dtype=int)
    for line in result.stdout.splitlines():
        if not line:
            continue
        cols = line.split("\t")
        if len(cols) < 3:
            continue
        try:
            pos = int(cols[1])
            depth = float(cols[2])
        except ValueError:
            continue
        if pos < 1 or pos > CHR3_LENGTH_BP:
            continue
        idx = min((pos - 1) // CHR3_WINDOW_BP, CHR3_N_WINDOWS - 1)
        sums[idx] += depth
        counts[idx] += 1

    expected_lengths = [CHR3_WINDOW_BP] * (CHR3_N_WINDOWS - 1) + [
        CHR3_LENGTH_BP - CHR3_WINDOW_BP * (CHR3_N_WINDOWS - 1)
    ]
    for i, expected in enumerate(expected_lengths):
        if counts[i] != expected:
            raise RuntimeError(
                f"Chromosome III window {i+1} returned {counts[i]} positions; "
                f"expected {expected}. Check the reference contig name/length and BAM."
            )
    means = (sums / counts).tolist()
    _CHR3_WINDOW_CACHE[bam_path] = tuple(means)
    return means


