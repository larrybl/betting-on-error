def write_chr3_audit(measurements: list, day0_chr3: float) -> None:
    """Write arithmetic, denominator-sensitivity and batch diagnostics.

    Window quantiles describe within-chromosome spread, NOT confidence intervals.
    Batch summaries describe these selected samples, NOT estimated batch effects.
    Alternative denominators are never used to modify the primary figure.
    """
    os.makedirs(AUX_DIR, exist_ok=True)
    wt = _CHR3_AUDIT[WT_FOUNDER]
    raw_min = _global_min_raw_from_audit(measurements)
    additive_offset = _global_additive_offset_from_audit(measurements)
    summaries, windows, chromosomes, sensitivity = [], [], [], []
    for sample, detail in _CHR3_AUDIT.items():
        meta = {**_sample_metadata(sample), "batch": detail["batch"],
                "wt_batch": detail["wt_batch"], "batch_relation_to_wt": detail["batch_relation_to_wt"]}
        baseline = detail["baseline"]["primary_depth"]
        wt_baseline = wt["baseline"]["primary_depth"]
        summaries.append({**meta, CHR3_RELDEPTH_FIELD: detail["value"],
                          CHR3_VALUE_FIELD: _relative_depth_to_scaled_index(detail["value"], additive_offset),
                          "raw_minimum_ratio": raw_min,
                          "additive_offset": additive_offset,
                          "baseline_mean_depth": baseline,
                          "wt_baseline_mean_depth": wt_baseline,
                          "raw_window_depth_ratio_to_wt": detail["raw_window_depth_ratio_to_wt"],
                          "baseline_depth_ratio_to_wt": detail["baseline_depth_ratio_to_wt"],
                          "window_q25": detail["window_q25"], "window_q75": detail["window_q75"],
                          "window_min": detail["window_min"], "window_max": detail["window_max"],
                          "windows_below_wt": detail["windows_below_wt"],
                          "windows_above_wt": detail["windows_above_wt"],
                          "n_windows": len(detail["ratios"]),
                          "chr3_weighted_window_mean_depth": detail["weighted_window_mean_depth"],
                          "chr3_coverage_mean_depth": detail["coverage_mean_depth"],
                          "depth_engine_ratio": detail["depth_engine_ratio"],
                          "audit_flags": ";".join(detail["flags"])})
        for i in range(CHR3_N_WINDOWS):
            start, end = i * CHR3_WINDOW_BP + 1, min((i + 1) * CHR3_WINDOW_BP, CHR3_LENGTH_BP)
            windows.append({**meta, "window_index": i + 1, "start_bp": start, "end_bp": end,
                            "length_bp": end - start + 1,
                            "sample_raw_mean_depth": detail["raw_windows"][i],
                            "wt_raw_mean_depth": wt["raw_windows"][i],
                            "sample_baseline_mean_depth": baseline, "wt_baseline_mean_depth": wt_baseline,
                            "sample_normalised_depth": detail["normalised_windows"][i],
                            "wt_normalised_depth": wt["normalised_windows"][i],
                            "wt_referenced_window_ratio": detail["ratios"][i]})
        for contig, label in ALL_CHROM_CONTIGS.items():
            record, reference = detail["records"].get(contig), wt["records"].get(contig)
            included = contig in detail["baseline"]["contigs"]
            depth = record["mean_depth"] if record else float("nan")
            ref_depth = reference["mean_depth"] if reference else float("nan")
            matched = ((depth / baseline) / (ref_depth / wt_baseline)
                       if np.isfinite(depth) and ref_depth > 0 else float("nan"))
            weight = record["length_bp"] / detail["baseline"]["total_length_bp"] if record and included else 0.0
            chromosomes.append({**meta, "chromosome": label, "contig": contig,
                                 "length_bp": record["length_bp"] if record else None,
                                 "raw_mean_depth": depth, "wt_raw_mean_depth": ref_depth,
                                 "coverage_pct": record["coverage_pct"] if record else None,
                                 "included_in_chr3_baseline": included,
                                 "baseline_length_weight": weight,
                                 "contribution_to_baseline_mean_depth": depth * weight if included else 0.0,
                                 "depth_over_chr3_baseline": depth / baseline,
                                 "wt_referenced_whole_chromosome_depth_ratio": matched})
        sensitivity.append({**meta, "primary_length_weighted_ratio": detail["value"],
                            "raw_minimum_ratio": raw_min,
                          "additive_offset": additive_offset,
                            "additively_lifted_copy_number_index": _relative_depth_to_scaled_index(detail["value"], additive_offset),
                            "diagnostic_median_denominator_ratio": detail["alternative_values"]["median_depth"],
                            "diagnostic_unweighted_denominator_ratio": detail["alternative_values"]["unweighted_mean_depth"],
                            "primary_baseline_mean_depth": baseline,
                            "median_chromosome_depth": detail["baseline"]["median_depth"],
                            "unweighted_mean_chromosome_depth": detail["baseline"]["unweighted_mean_depth"]})
    for filename, rows in (("chr3_sample_diagnostics.csv", summaries),
                           ("chr3_window_diagnostics.csv", windows),
                           ("chr3_chromosome_diagnostics.csv", chromosomes),
                           ("chr3_denominator_sensitivity.csv", sensitivity)):
        _write_rows(os.path.join(AUX_DIR, filename), list(rows[0]), rows)
    plot_rows = figure_6_2_plot_rows(measurements, day0_chr3)
    _write_rows(os.path.join(AUX_DIR, "Figure_6.2_plot_values.csv"),
                ["sample", "regime", "day", "phase", "point_role", "source_reused_across_regimes",
                 "batch", CHR3_RELDEPTH_FIELD, CHR3_VALUE_FIELD], plot_rows)
    batch_rows = []
    for batch in sorted({d["batch"] for d in _CHR3_AUDIT.values()}):
        members = [d for d in _CHR3_AUDIT.values() if d["batch"] == batch]
        values = [d["value"] for d in members]
        controls = [c["wt_referenced_whole_chromosome_depth_ratio"] for c in chromosomes
                    if c["batch"] == batch and c["included_in_chr3_baseline"]
                    and c["sample"] != WT_FOUNDER
                    and np.isfinite(c["wt_referenced_whole_chromosome_depth_ratio"])]
        batch_rows.append({"batch": batch, "n_samples": len(members),
                           "samples": ";".join(d["sample"] for d in members),
                           "n_competition_samples": sum(d["sample"] in SAMPLES for d in members),
                           "includes_wt_founder": any(d["sample"] == WT_FOUNDER for d in members),
                           "chr3_reference_ratio_min": min(values),
                           "chr3_reference_ratio_median": float(np.median(values)),
                           "chr3_reference_ratio_max": max(values),
                           "n_below_wt_reference": sum(v < 1.0 for v in values),
                           "other_chromosome_wt_ratio_median_excluding_wt_self": float(np.median(controls)) if controls else None,
                           "batch_correction_applied": False,
                           "interpretation": "Descriptive only; sample composition and run effects are not separated."})
    _write_rows(os.path.join(AUX_DIR, "chr3_batch_diagnostics.csv"), list(batch_rows[0]), batch_rows)
    _write_chr3_manifest(measurements)
    with open(os.path.join(AUX_DIR, "Figure_6.2_caption.txt"), "w", encoding="utf-8") as handle:
        handle.write(CHR3_CAPTION + "\n")
    print(f"  Chromosome III audit tables written to {AUX_DIR}/")


def _write_chr3_manifest(measurements: list) -> None:
    """Record exactly which scale and inputs were used, without hashing large BAMs."""
    source_path = os.path.abspath(__file__)
    with open(source_path, "rb") as handle:
        source_hash = hashlib.sha256(handle.read()).hexdigest()
    try:
        proc = subprocess.run(["samtools", "--version"], capture_output=True, text=True, check=True)
        tool_version = proc.stdout.splitlines()[0]
    except (OSError, subprocess.SubprocessError, IndexError):
        tool_version = "unavailable"
    inputs = []
    for sample in dict.fromkeys(SAMPLES + FOUNDER_SAMPLES):
        path = os.path.abspath(os.path.join(BAM_DIR, sample + BAM_SUFFIX))
        exists = os.path.isfile(path)
        stat = os.stat(path) if exists else None
        inputs.append({"sample": sample, "path": path, "exists": exists,
                       "size_bytes": stat.st_size if stat else None,
                       "modified_time_ns": stat.st_mtime_ns if stat else None,
                       "configured_batch": SAMPLE_BATCH.get(sample),
                       "used_for_chr3": sample in _CHR3_AUDIT})
    manifest = {
        "script_version": SCRIPT_VERSION, "created_utc": datetime.now(timezone.utc).isoformat(),
        "source_path": source_path, "source_sha256": source_hash,
        "samtools_version": tool_version, "method": CHR3_METHOD,
        "plotted_value_field": CHR3_VALUE_FIELD,
        "measurement": "Chromosome III abundance index linearly rescaled so the minimum plotted raw ratio equals 1.0",
        "raw_relative_depth_formula": "R = median_w[(sample_window_depth/sample_baseline)/(WT_window_depth/WT_baseline)]",
        "scaling_formula": "index = R + max(0, 1 - min(R across plotted competition samples + shared day-zero mixture))",
        "raw_minimum_ratio": _global_min_raw_from_audit(measurements),
        "additive_offset": _global_additive_offset_from_audit(measurements),
        "baseline": "Length-weighted mean depth of nuclear chromosomes excluding III and XII",
        "wt_reference_sample": WT_FOUNDER, "wt_reference_batch": SAMPLE_BATCH.get(WT_FOUNDER),
        "window_length_bp": CHR3_WINDOW_BP, "chromosome_III_length_bp": CHR3_LENGTH_BP,
        "n_windows": CHR3_N_WINDOWS, "minimum_mapping_quality": MIN_MAPQ,
        "excluded_read_flags": EXCLUDE_FLAGS_HEX,
        "coverage_arguments": ["coverage", "-q", str(MIN_MAPQ), "--ff", EXCLUDE_FLAGS_HEX],
        "depth_arguments": ["depth", "-aa", "-Q", str(MIN_MAPQ), "-G", EXCLUDE_FLAGS_HEX,
                            "-r", CHR3_CONTIG_NAME],
        "batch_correction_applied": False, "batch_labels_source": "SAMPLE_BATCH configuration; not re-inferred",
        "floor_rescaling_applied": False, "additive_lift_applied": True,
        "uncertainty": "Window quantiles are descriptive spread, not confidence intervals or biological replicates",
        "shared_day0": {"source": MIX_FOUNDER, "used_for_all_regimes": True,
                        "independent_samples": 1, "note": "Shared anchor retained from source; not a separate baseline for each lineage"},
        "compatibility_aliases": {"chr3_copy_ratio": CHR3_VALUE_FIELD, "copy_chrIII": CHR3_VALUE_FIELD},
        "csv_note": "Legacy per-chromosome ratios are exported separately, with legacy_depth_ratio_ prefixes",
        "n_competition_samples": len(measurements), "inputs": inputs,
    }
    with open(os.path.join(AUX_DIR, "chr3_run_manifest.json"), "w", encoding="utf-8") as handle:
        json.dump(manifest, handle, indent=2, allow_nan=False)
        handle.write("\n")


def main(argv=None):
    global BAM_DIR, OUT_DIR
    parser = argparse.ArgumentParser(description="Figure 6.2 relative-read-depth analysis and audit.")
    parser.add_argument("--chr3-only", action="store_true",
                        help="Generate Figure 6.2 and its audit without variant tables or GFF.")
    parser.add_argument("--bam-dir", default=BAM_DIR, help="Directory containing BAM files; default: <script stem> Additional Files/BAM Files.")
    parser.add_argument("--out-dir", default=OUT_DIR, help="Output directory (separate audit folder by default).")
    args = parser.parse_args(argv)
    BAM_DIR = os.path.abspath(os.path.expanduser(args.bam_dir))
    OUT_DIR = os.path.abspath(os.path.expanduser(args.out_dir))
    if not os.path.isdir(BAM_DIR):
        parser.exit(1, f"ERROR: BAM directory not found: {BAM_DIR}\nPlace BAM and .bai files in the script-specific Additional Files/BAM Files directory, or set --bam-dir / WGS_BAM_DIR.\n")
    if not any(name.endswith(BAM_SUFFIX) for name in os.listdir(BAM_DIR)):
        parser.exit(1, f"ERROR: No *{BAM_SUFFIX} files found in: {BAM_DIR}\nPlace the BAM files and their .bai indexes in that directory.\n")
    if shutil.which("samtools") is None:
        parser.exit(1, "ERROR: samtools is not on PATH. No BAM analysis has been performed.\n")
    # Reset per-run caches so programmatic repeated calls do not reuse old measurements.
    for cache in (_MEASURE_CACHE, _COVERAGE_RECORD_CACHE, _CHR3_WINDOW_CACHE,
                  _CHR3_DETAIL_CACHE, _CHR3_AUDIT):
        cache.clear()
    measurements = measure_samples()
    if not measurements:
        parser.exit(1, "ERROR: No competition samples could be measured; check BAM_DIR and BAM_SUFFIX.\n")
    day0_chr3, founder_scaled = apply_chr3_window_method(measurements)
    os.makedirs(OUT_DIR, exist_ok=True)
    # Save the audit BEFORE other analyses, so unrelated failures do not hide the inputs.
    write_chr3_audit(measurements, day0_chr3)
    day0_relative = _CHR3_AUDIT.get(MIX_FOUNDER, {}).get("value", float("nan"))
    stale_audit_figure = os.path.join(OUT_DIR, CHR3_RELDEPTH_AUDIT_FIGURE_NAME)
    if os.path.exists(stale_audit_figure):
        try:
            os.remove(stale_audit_figure)
        except OSError:
            pass
    report_copy_number(measurements, day0_chr3, founder_scaled=founder_scaled)
    if args.chr3_only:
        make_copy_number_regime_lines(measurements, day0_chr3,
                                      out_path=os.path.join(OUT_DIR, CHR3_FIGURE_NAME))
        write_csvs(measurements, [], [], [], write_variant_outputs=False)
        print(f"\nDone: Figure 6.2 and its audit are in {OUT_DIR}/")
        return

    # Marker and variant calculations retain the source algorithms.
    variants = load_variants()
    gene_index = build_gene_index(parse_gff(GFF_PATH))
    table = index_variants(variants)
    diversity_rows = shannon_diversity(table)
    day0_div = shannon_day0(table)
    heat_rows, all_heat_rows = test_heat_vs_cold(table, gene_index)
    time_rows = test_change_over_time(table, gene_index)

    # Supervisor-requested analysis: founder variants are excluded BEFORE
    # Fisher testing and BEFORE Benjamini-Hochberg correction.
    de_novo_table = new_mutation_table(table)
    de_novo_heat_rows, de_novo_all_heat_rows = test_heat_vs_cold(de_novo_table, gene_index)
    de_novo_time_rows = test_change_over_time(de_novo_table, gene_index)

    report_competition(measurements)
    report_founder_markers()
    report_variants(heat_rows, time_rows)
    report_new_mutations(de_novo_heat_rows, de_novo_time_rows, len(de_novo_all_heat_rows))
    make_figures(measurements, diversity_rows, day0_chr3,
                 day0_diversity=day0_div, all_heat_rows=all_heat_rows,
                 wt_ref=founder_scaled.get("WT", float("nan")), time_rows=time_rows,
                 de_novo_all_heat_rows=de_novo_all_heat_rows)
    write_csvs(measurements, heat_rows, time_rows, diversity_rows,
               de_novo_heat_rows=de_novo_heat_rows, de_novo_time_rows=de_novo_time_rows)
    print("Done.")


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, OSError) as exc:
        sys.exit(f"ERROR: {exc}")
