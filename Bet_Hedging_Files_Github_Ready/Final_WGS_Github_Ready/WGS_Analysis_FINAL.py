def _global_min_raw_from_audit(measurements: list) -> float:
    """Return the lowest raw ratio among values actually plotted in Figure 6.2."""
    vals = [
        _CHR3_AUDIT.get(row["sample"], {}).get("value", float("nan"))
        for row in measurements
    ]
    vals.append(_CHR3_AUDIT.get(MIX_FOUNDER, {}).get("value", float("nan")))
    vals = [float(v) for v in vals if np.isfinite(v)]
    if not vals:
        raise RuntimeError("No finite Figure 6.2 raw ratios are available to define the additive lift.")
    return min(vals)


def _global_additive_offset_from_audit(measurements: list) -> float:
    """Return the single upward offset that places the observed minimum at 1.0."""
    return max(0.0, 1.0 - _global_min_raw_from_audit(measurements))


def _chr3_plot_limits(values) -> tuple:
    """Plot the rescaled abundance index with the observed minimum at 1.0."""
    finite = [float(v) for v in values if np.isfinite(v)] + [1.0]
    high = max(finite)
    padding = max(0.05, 0.14 * max(high - 1.0, 0.05))
    return 0.98, high + padding


