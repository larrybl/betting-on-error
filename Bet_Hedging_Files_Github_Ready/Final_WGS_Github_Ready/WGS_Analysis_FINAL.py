def function_label(note_text):
    """One coarse functional word for a gene, from its GFF description."""
    if not note_text:
        return "unannotated"
    low = note_text.lower()
    for label, keywords in FUNCTION_KEYWORDS:
        if any(k in low for k in keywords):
            return label
    if "putative" in low or "unknown" in low or "uncharacterized" in low:
        return "uncharacterised"
    return "other"


def parse_gff(path):
    """Returns {GENE_NAME: (chrom, start, end, strand, function_label)}."""
    genes = {}
    try:
        handle = open(path)
    except FileNotFoundError:
        print(f"  ! GFF not found at {path} -- hits will be reported without gene names.")
        return genes
    with handle as f:
        for line in f:
            if not line.strip() or line.startswith("#"):
                continue
            cols = line.rstrip("\n").split("\t")
            if len(cols) < 9:
                continue
            seqid, _source, ftype, start, end, _score, strand, _frame, attrs = cols
            if ftype.lower() not in ("gene", "orf", "ncrna_gene"):
                continue
            attr_dict = {}
            for pair in attrs.strip(";").split(";"):
                if "=" in pair:
                    k, v = pair.split("=", 1)
                    attr_dict[k.strip()] = v.strip()
            names = {attr_dict[k].upper() for k in ("Name", "gene", "gene_name", "ID", "locus_tag")
                     if k in attr_dict}
            note = unquote(attr_dict.get("Note", "") or attr_dict.get("description", ""))
            record = (seqid, int(start), int(end), strand, function_label(note))
            for n in names:
                genes[n] = record
    return genes


def build_gene_index(gene_table):
    """Group genes by chromosome once, so annotation is fast."""
    index = defaultdict(list)
    for name, (chrom, start, end, strand, func) in gene_table.items():
        index[canonical_chrom(chrom)].append((start, end, strand, name, func))
    for chrom in index:
        index[chrom].sort()
    return index


def annotate(chrom, pos, gene_index):
    """Gene name(s) at this position, or 'intergenic'. Purely a label --
    annotation happens AFTER the statistics, never as a filter."""
    hits, funcs = {}, {}
    for start, end, strand, name, func in gene_index.get(canonical_chrom(chrom), []):
        if start <= pos <= end:
            rel = "body"
        elif strand == "+" and (start - PROMOTER_WINDOW) <= pos < start:
            rel = "promoter"
        elif strand == "-" and end < pos <= (end + PROMOTER_WINDOW):
            rel = "promoter"
        else:
            continue
        key = (start, end)
        prev = hits.get(key)
        # prefer a common gene name over a systematic YXX000W-style name
        if prev is None or (_SYSTEMATIC_NAME_RE.match(prev) and not _SYSTEMATIC_NAME_RE.match(name)):
            hits[key] = name
            funcs[key] = func
    if not hits:
        return "intergenic", "-"
    gene = ";".join(sorted(set(hits.values())))
    func = sorted({f for f in funcs.values() if f})[0] if funcs else "-"
    return gene, func


def normalize_indel(pos, ref, alt):
    """Collapse the two equivalent ways a caller can write the same indel, so
    one real mutation isn't split into two half-strength variants."""
    if len(ref) == len(alt):
        return (pos, ref, alt)
    if len(alt) > len(ref):
        inserted = alt[len(ref):] if alt.startswith(ref) else alt[:len(alt) - len(ref)]
        return (pos, "INDEL", inserted)
    deleted = ref[len(alt):] if ref.startswith(alt) else ref[:len(ref) - len(alt)]
    return (pos, "INDEL", deleted)


def load_variants():
    """Load and merge both WGS run tables."""
    rows = []
    seen_samples = defaultdict(set)
    for run_id, path in (("run1", CSV_PATH_RUN1), ("run2", CSV_PATH_RUN2)):
        try:
            handle = open(path)
        except FileNotFoundError:
            print(f"  ! variant table not found: {path}")
            continue
        with handle as f:
            for r in csv.DictReader(f):
                try:
                    freq = float(r["Variant frequency"].replace("%", ""))
                    count = int(r["Variant Count"])
                    coverage = int(r["Coverage"])
                except (ValueError, KeyError):
                    continue
                sample = r["Sample"]
                regime_day = SAMPLE_INFO.get(sample)
                rows.append({
                    "sample": sample, "run": run_id,
                    "chrom": r["Chromosome"], "pos": int(r["Position"]),
                    "ref": r["Reference Allele"], "alt": r["Variant Allele"],
                    "freq": freq, "count": count, "coverage": coverage,
                    "regime": regime_day[0] if regime_day else "?",
                    "day": regime_day[1] if regime_day else None,
                })
                seen_samples[run_id].add(sample)
    # if a sample appears in both runs, keep run2 (more recent) to avoid double counting
    overlap = seen_samples["run1"] & seen_samples["run2"]
    if overlap:
        print(f"  ! {len(overlap)} sample(s) in both runs; keeping run2 rows for those.")
        rows = [v for v in rows if not (v["run"] == "run1" and v["sample"] in overlap)]
    return rows


def index_variants(variants):
    """key -> {sample: (variant_reads, coverage, freq)}, using normalized keys."""
    table = defaultdict(dict)
    for v in variants:
        if v["coverage"] < MIN_COVERAGE:
            continue
        key = (canonical_chrom(v["chrom"]),) + normalize_indel(v["pos"], v["ref"], v["alt"])
        prev = table[key].get(v["sample"])
        if prev is None or v["freq"] > prev[2]:
            table[key][v["sample"]] = (v["count"], v["coverage"], v["freq"])
    return table


def classify_founder_origin(per_sample):
    """Where did this variant come from, based on the two founder monocultures?
    This is the cleanest available ground truth -- it predates every day of
    the experiment, so it doesn't depend on the marker attribution at all."""
    wt = per_sample.get(WT_FOUNDER)
    edit = per_sample.get(EDIT_FOUNDER)
    wt_has = wt is not None and wt[2] >= MIN_FREQ_PCT
    edit_has = edit is not None and edit[2] >= MIN_FREQ_PCT
    if wt_has and edit_has:
        return "both founders"
    if edit_has:
        return "EDIT founder only"
    if wt_has:
        return "WT founder only"
    return "de novo (neither founder)"


def is_new_mutation_candidate(per_sample):
    """Return True only when the variant was not detected in either sequenced founder.

    'New mutation' is operationally defined here as absent at the configured
    MIN_FREQ_PCT threshold from both pure founder call sets. A variant present
    below the calling/detection threshold at the start cannot be excluded by
    these bulk data, so thesis text should say 'not detected in either founder'
    rather than claiming absolute proof that every retained variant arose de novo.
    """
    return classify_founder_origin(per_sample) == "de novo (neither founder)"


def new_mutation_table(table):
    """Filter founder variants OUT BEFORE any statistical testing or BH correction."""
    return {key: per_sample for key, per_sample in table.items()
            if is_new_mutation_candidate(per_sample)}


