def _coverage_records(bam_path: str):
    """Read and cache the unmodified samtools coverage table for one BAM.

    The samtools arguments match the uploaded script. Lengths and raw depths
    are retained so that every normalising denominator can be audited.
    """
    if bam_path in _COVERAGE_RECORD_CACHE:
        return _COVERAGE_RECORD_CACHE[bam_path]
    if not os.path.isfile(bam_path):
        print(f"    ! BAM not found, skipping: {bam_path}")
        return None
    cmd = ["samtools", "coverage", "-q", str(MIN_MAPQ),
           "--ff", EXCLUDE_FLAGS_HEX, bam_path]
    try:
        result = subprocess.run(cmd, capture_output=True, text=True, check=True)
    except FileNotFoundError as exc:
        raise RuntimeError("samtools not found on PATH.") from exc
    except subprocess.CalledProcessError as exc:
        raise RuntimeError(f"samtools coverage failed for {bam_path}:\n{exc.stderr}") from exc
    lines = [line for line in result.stdout.splitlines() if line.strip()]
    if not lines:
        raise RuntimeError(f"samtools coverage returned no table for {bam_path}.")
    reader = csv.DictReader(lines, delimiter="\t")
    reader.fieldnames = [name.lstrip("#") for name in (reader.fieldnames or [])]
    required = {"rname", "startpos", "endpos", "meandepth"}
    if not required.issubset(reader.fieldnames):
        raise RuntimeError(f"Unexpected samtools coverage columns for {bam_path}: {reader.fieldnames}")
    records = {}
    for row in reader:
        name = row["rname"]
        try:
            start, end = int(row["startpos"]), int(row["endpos"])
            depth = float(row["meandepth"])
            coverage = float(row.get("coverage", "nan"))
        except (TypeError, ValueError) as exc:
            raise RuntimeError(f"Invalid coverage record for {name} in {bam_path}.") from exc
        if start != 1 or end < start or not np.isfinite(depth) or depth < 0:
            raise RuntimeError(f"Invalid full-contig coverage record for {name} in {bam_path}.")
        if name in records:
            raise RuntimeError(f"Duplicate coverage record for {name} in {bam_path}.")
        records[name] = {"start_bp": start, "end_bp": end,
                         "length_bp": end - start + 1, "mean_depth": depth,
                         "coverage_pct": coverage}
    _COVERAGE_RECORD_CACHE[bam_path] = records
    return records


def _baseline_summary(records: dict) -> dict:
    """Primary denominator and diagnostic alternatives; exclude III and XII.

    Missing baseline chromosomes are an error, not a reason to silently change
    the set of chromosomes used for a particular sample.
    """
    contigs = [c for c, label in ALL_CHROM_CONTIGS.items()
               if label not in {"chrIII", "chrXII"}]
    missing = [c for c in contigs if c not in records]
    if missing:
        raise RuntimeError("Missing baseline chromosomes: " + ", ".join(missing))
    lengths = np.asarray([records[c]["length_bp"] for c in contigs], dtype=float)
    depths = np.asarray([records[c]["mean_depth"] for c in contigs], dtype=float)
    if np.any(lengths <= 0) or np.any(~np.isfinite(depths)) or np.any(depths < 0):
        raise RuntimeError("Invalid chromosome lengths/depths in normalising set.")
    total_length = int(np.sum(lengths))
    weighted = float(np.sum(depths * lengths) / total_length)
    if not np.isfinite(weighted) or weighted <= 0:
        raise RuntimeError("Other-chromosome length-weighted depth is not positive.")
    return {"primary_depth": weighted, "median_depth": float(np.median(depths)),
            "unweighted_mean_depth": float(np.mean(depths)),
            "total_length_bp": total_length, "contigs": contigs}


def measure_chr3_details(bam_sample: str):
    """Keep the raw 32-window profile, baseline and chromosome coverage table."""
    bam_path = os.path.join(BAM_DIR, bam_sample + BAM_SUFFIX)
    if bam_path in _CHR3_DETAIL_CACHE:
        return _CHR3_DETAIL_CACHE[bam_path]
    records = _coverage_records(bam_path)
    if records is None:
        return None
    if CHR3_CONTIG_NAME not in records:
        raise RuntimeError(f"{bam_sample}: chromosome III contig {CHR3_CONTIG_NAME} is missing.")
    if records[CHR3_CONTIG_NAME]["length_bp"] != CHR3_LENGTH_BP:
        raise RuntimeError(f"{bam_sample}: chromosome III length differs from {CHR3_LENGTH_BP} bp.")
    baseline = _baseline_summary(records)
    raw = np.asarray(_samtools_depth_chr3_windows(bam_path), dtype=float)
    if raw.shape != (CHR3_N_WINDOWS,) or np.any(~np.isfinite(raw)) or np.any(raw < 0):
        raise RuntimeError(f"{bam_sample}: invalid chromosome III window depths.")
    result = {"sample": bam_sample, "bam_path": bam_path, "records": records,
              "baseline": baseline, "raw_windows": raw,
              "normalised_windows": raw / baseline["primary_depth"]}
    _CHR3_DETAIL_CACHE[bam_path] = result
    return result


def _wt_reference(detail: dict, wt_detail: dict) -> dict:
    """Compute the original estimator without floors, clipping or batch shifts."""
    wt = np.asarray(wt_detail["normalised_windows"], dtype=float)
    own = np.asarray(detail["normalised_windows"], dtype=float)
    if wt.shape != (CHR3_N_WINDOWS,) or np.any(~np.isfinite(wt)) or np.any(wt <= 0):
        raise RuntimeError("WT founder has a missing, nonfinite or zero-depth chromosome III window.")
    if own.shape != wt.shape or np.any(~np.isfinite(own)) or np.any(own < 0):
        raise RuntimeError(f"Invalid sample window profile: {detail['sample']}.")
    ratios = own / wt
    sample = detail["sample"]
    batch, wt_batch = SAMPLE_BATCH.get(sample), SAMPLE_BATCH.get(WT_FOUNDER)
    relation = ("unknown" if not batch or not wt_batch else
                "same_batch" if batch == wt_batch else "different_batch")
    q25, q75 = np.percentile(ratios, [25, 75])
    median = float(np.median(ratios))
    raw_ratio = float(np.median(detail["raw_windows"] / wt_detail["raw_windows"]))
    denominator_ratio = detail["baseline"]["primary_depth"] / wt_detail["baseline"]["primary_depth"]
    if not np.isclose(median, raw_ratio / denominator_ratio, rtol=1e-12, atol=1e-12):
        raise RuntimeError("Window-ratio reconstruction failed; numerator and denominator disagree.")
    alternatives = {}
    for name in ("median_depth", "unweighted_mean_depth"):
        b, bw = detail["baseline"][name], wt_detail["baseline"][name]
        alternatives[name] = (float(np.median((detail["raw_windows"] / b) /
                                            (wt_detail["raw_windows"] / bw)))
                              if b > 0 and bw > 0 else float("nan"))
    lengths = np.asarray([min(CHR3_WINDOW_BP, CHR3_LENGTH_BP - i * CHR3_WINDOW_BP)
                          for i in range(CHR3_N_WINDOWS)])
    raw_mean = float(np.average(detail["raw_windows"], weights=lengths))
    coverage_mean = detail["records"][CHR3_CONTIG_NAME]["mean_depth"]
    flags = []
    if median < 1.0:
        flags.append("BELOW_WT_REFERENCE")
    if relation == "different_batch":
        flags.append("CROSS_BATCH_WT_REFERENCE")
    elif relation == "unknown":
        flags.append("BATCH_UNKNOWN")
    if np.any(ratios == 0):
        flags.append("ZERO_DEPTH_WINDOW")
    engine_ratio = raw_mean / coverage_mean if coverage_mean > 0 else float("nan")
    if np.isfinite(engine_ratio) and abs(engine_ratio - 1.0) > 0.01:
        flags.append("DEPTH_COVERAGE_DIFFER_BY_OVER_1_PERCENT")
    return {**detail, "batch": batch or "unknown", "wt_batch": wt_batch or "unknown",
            "batch_relation_to_wt": relation, "ratios": ratios,
            "value": float(median), "window_q25": float(q25), "window_q75": float(q75),
            "window_min": float(np.min(ratios)), "window_max": float(np.max(ratios)),
            "windows_below_wt": int(np.sum(ratios < 1.0)),
            "windows_above_wt": int(np.sum(ratios > 1.0)),
            "raw_window_depth_ratio_to_wt": raw_ratio,
            "baseline_depth_ratio_to_wt": denominator_ratio,
            "alternative_values": alternatives, "weighted_window_mean_depth": raw_mean,
            "coverage_mean_depth": coverage_mean, "depth_engine_ratio": engine_ratio,
            "flags": flags}


def _relative_depth_to_scaled_index(value: float, offset: float) -> float:
    """Lift one WT-referenced depth value by one global additive offset.

    Thesis-facing index = R + offset, where offset = max(0, 1 - R_min).
    The same constant is added to every plotted point. This preserves every
    absolute difference and temporal rise/fall/rebound while ensuring no plotted
    value is below 1.0. The raw WT-referenced ratio R is retained separately.
    """
    if not np.isfinite(value) or not np.isfinite(offset):
        return float("nan")
    return float(value) + float(offset)


