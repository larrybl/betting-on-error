def benjamini_hochberg(pvals):
    """Standard BH step-up FDR. Returns q-values in the input order."""
    n = len(pvals)
    if n == 0:
        return []
    order = sorted(range(n), key=lambda i: pvals[i])
    q = [1.0] * n
    running_min = 1.0
    for rank in range(n, 0, -1):
        idx = order[rank - 1]
        val = pvals[idx] * n / rank
        running_min = min(running_min, val)
        q[idx] = min(1.0, running_min)
    return q


def fisher_on_counts(var_a, cov_a, var_b, cov_b):
    """Fisher's exact test comparing two variant/reference read ratios.
    Plain-language: 'out of all the reads I looked at, is the proportion
    carrying this mutation different between group A and group B?'"""
    ref_a, ref_b = max(cov_a - var_a, 0), max(cov_b - var_b, 0)
    if (var_a + ref_a) == 0 or (var_b + ref_b) == 0:
        return float("nan")
    _odds, p = stats.fisher_exact([[var_a, ref_a], [var_b, ref_b]])
    return p


def pooled_counts(per_sample, sample_list):
    var = sum(per_sample[s][0] for s in sample_list if s in per_sample)
    cov = sum(per_sample[s][1] for s in sample_list if s in per_sample)
    freqs = [per_sample[s][2] for s in sample_list if s in per_sample]
    mean_freq = float(np.mean(freqs)) if freqs else 0.0
    return var, cov, mean_freq


def test_heat_vs_cold(table, gene_index):
    """Which variants sit at a different frequency in heat-exposed samples
    than in the 30C control samples?

    CAVEAT, stated plainly: reads are pooled across samples within each group,
    which treats the group as one big sample. That is the simple, readable
    test -- but it does not account for sample-to-sample variability, so a
    variant driven by one unusual sample can still reach significance. Treat
    hits as a ranked shortlist, not proof."""
    heat_samples = [s for s in SAMPLES if SAMPLE_INFO[s][0] in HEAT_REGIMES]
    cold_samples = [s for s in SAMPLES if SAMPLE_INFO[s][0] in COLD_REGIMES]

    rows, pvals = [], []
    for key, per_sample in table.items():
        if not any(v[2] >= MIN_FREQ_PCT for v in per_sample.values()):
            continue
        hv, hc, hf = pooled_counts(per_sample, heat_samples)
        cv, cc, cf = pooled_counts(per_sample, cold_samples)
        if hc == 0 or cc == 0:
            continue
        diff = hf - cf
        p = fisher_on_counts(hv, hc, cv, cc)
        if p != p:
            continue
        chrom, pos, ref, alt = key
        rows.append({
            "chrom": chrom, "pos": pos, "ref": ref, "alt": alt,
            "gene": annotate(chrom, pos, gene_index)[0],
            "function": annotate(chrom, pos, gene_index)[1],
            "heat_freq": hf, "cold_freq": cf, "diff": diff,
            "origin": classify_founder_origin(per_sample),
            "p": p,
        })
        pvals.append(p)
    qvals = benjamini_hochberg(pvals)
    for row, q in zip(rows, qvals):
        row["q"] = q
    all_rows = sorted(rows, key=lambda r: (-abs(r["diff"]), r["q"]))
    significant = [r for r in all_rows
                   if r["q"] <= FDR_ALPHA and abs(r["diff"]) >= MIN_ABS_FREQ_DIFF]
    return significant, all_rows


def test_change_over_time(table, gene_index):
    """Within each condition separately: does the variant sit at a different
    frequency at the last timepoint than at the first?"""
    rows, pvals = [], []
    for regime in REGIME_ORDER:
        regime_samples = sorted([s for s in SAMPLES if SAMPLE_INFO[s][0] == regime],
                                key=lambda s: SAMPLE_INFO[s][1])
        if len(regime_samples) < 2:
            continue
        first, last = regime_samples[0], regime_samples[-1]
        for key, per_sample in table.items():
            if first not in per_sample or last not in per_sample:
                continue
            if not any(v[2] >= MIN_FREQ_PCT for v in per_sample.values()):
                continue
            fv, fc, ff = per_sample[first][0], per_sample[first][1], per_sample[first][2]
            lv, lc, lf = per_sample[last][0], per_sample[last][1], per_sample[last][2]
            diff = lf - ff
            if abs(diff) < MIN_ABS_FREQ_DIFF:
                continue
            p = fisher_on_counts(lv, lc, fv, fc)
            if p != p:
                continue
            chrom, pos, ref, alt = key
            rows.append({
                "regime": regime, "chrom": chrom, "pos": pos, "ref": ref, "alt": alt,
                "gene": annotate(chrom, pos, gene_index)[0],
                "function": annotate(chrom, pos, gene_index)[1],
                "first_day": SAMPLE_INFO[first][1], "last_day": SAMPLE_INFO[last][1],
                "first_freq": ff, "last_freq": lf, "diff": diff,
                "origin": classify_founder_origin(per_sample),
                "p": p,
            })
            pvals.append(p)
    qvals = benjamini_hochberg(pvals)
    for row, q in zip(rows, qvals):
        row["q"] = q
    rows = [r for r in rows if r["q"] <= FDR_ALPHA]
    rows.sort(key=lambda r: (REGIME_ORDER.index(r["regime"]), -abs(r["diff"])))
    return rows


def shannon_for_sample(table, sample):
    freqs = [v[sample][2] for v in table.values()
             if sample in v and v[sample][2] >= MIN_FREQ_PCT]
    total = sum(freqs)
    if total > 0:
        h = -sum((f / total) * math.log(f / total) for f in freqs if f > 0)
    else:
        h = 0.0
    return len(freqs), h


def shannon_day0(table):
    """Day-0 diversity, taken from the 50/50 starting mix sample."""
    richness, h = shannon_for_sample(table, MIX_FOUNDER)
    return {"sample": MIX_FOUNDER, "day": 0, "richness": richness, "shannon": h}


def shannon_diversity(table):
    """Shannon index per sample, treating each variant's frequency as a
    relative abundance. Falls as a few variants sweep to dominance; rises
    when many variants coexist at similar frequencies."""
    rows = []
    for sample in SAMPLES:
        richness, h = shannon_for_sample(table, sample)
        regime, day = SAMPLE_INFO[sample]
        rows.append({"sample": sample, "regime": regime, "day": day,
                     "richness": richness, "shannon": h})
    rows.sort(key=lambda r: (REGIME_ORDER.index(r["regime"]), r["day"]))
    return rows


