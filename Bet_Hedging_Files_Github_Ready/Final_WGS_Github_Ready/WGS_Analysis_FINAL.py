def make_de_novo_volcano_figure(all_rows, out_path):
    """Figure 6.3b: new-mutation candidates only.

    Founder-specific and founder-shared variants have already been excluded
    BEFORE Fisher testing and Benjamini-Hochberg correction. Grey points are
    tested new-mutation candidates that fail one or both reporting thresholds;
    coloured points pass q <= FDR_ALPHA and |difference| >= MIN_ABS_FREQ_DIFF.
    """
    if not all_rows:
        print("  No founder-absent variants were testable; Figure 6.3b not written.")
        return
    diffs = np.asarray([r["diff"] for r in all_rows], dtype=float)
    qs = np.asarray([max(r["q"], 1e-300) for r in all_rows], dtype=float)
    neglogq = -np.log10(qs)
    sig = (qs <= FDR_ALPHA) & (np.abs(diffs) >= MIN_ABS_FREQ_DIFF)
    up = sig & (diffs > 0)
    down = sig & (diffs < 0)
    nonsig = ~sig

    fig, ax = plt.subplots(figsize=(8.6, 6.0))
    ax.scatter(diffs[nonsig], neglogq[nonsig], s=20, marker="o", c="#C9C9C9",
               alpha=0.55, edgecolors="none", label="Does not pass both thresholds", zorder=2)
    ax.scatter(diffs[down], neglogq[down], s=48, marker="o", c=COLD_COLOR,
               alpha=0.9, edgecolors="white", linewidths=0.6,
               label="Higher at constant 30 °C", zorder=3)
    ax.scatter(diffs[up], neglogq[up], s=48, marker="o", c=HOT_COLOR,
               alpha=0.9, edgecolors="white", linewidths=0.6,
               label="Higher in regimes containing heat", zorder=3)
    ax.axvline(MIN_ABS_FREQ_DIFF, color="#666666", lw=1.0, ls="--", zorder=1)
    ax.axvline(-MIN_ABS_FREQ_DIFF, color="#666666", lw=1.0, ls="--", zorder=1)
    ax.axhline(-math.log10(FDR_ALPHA), color="#666666", lw=1.0, ls="--", zorder=1)

    # Label EVERY significant candidate. Gene-annotated sites use the gene name;
    # intergenic sites use chromosome:position so no significant point is left anonymous.
    significant_rows = [r for r in all_rows
                        if r["q"] <= FDR_ALPHA
                        and abs(r["diff"]) >= MIN_ABS_FREQ_DIFF]

    def de_novo_label(r):
        gene = _variant_gene_label(r)
        if gene is not None:
            return gene
        return f"{short_chrom(r['chrom'])}:{int(r['pos']):,}"

    ranked = sorted(significant_rows,
                    key=lambda r: -(abs(r["diff"]) * -math.log10(max(r["q"], 1e-300))))

    # Spread labels vertically on each side to reduce collisions.
    left = [r for r in ranked if r["diff"] < 0]
    right = [r for r in ranked if r["diff"] >= 0]

    def label_positions(rows):
        if not rows:
            return {}
        ys = {id(r): -math.log10(max(r["q"], 1e-300)) for r in rows}
        ordered = sorted(rows, key=lambda r: ys[id(r)])
        all_y = list(ys.values())
        span = max(max(all_y) - min(all_y), 1.0)
        gap = max(0.16, 0.045 * span)
        placed = {}
        last = None
        for r in ordered:
            y = ys[id(r)]
            if last is not None:
                y = max(y, last + gap)
            placed[id(r)] = y
            last = y
        return placed

    label_y = label_positions(left)
    label_y.update(label_positions(right))

    x_span = max(float(np.max(diffs) - np.min(diffs)), 1.0)
    for r in ranked:
        x = r["diff"]
        y = -math.log10(max(r["q"], 1e-300))
        dx = 0.055 * x_span if x >= 0 else -0.055 * x_span
        ax.annotate(de_novo_label(r), xy=(x, y),
                    xytext=(x + dx, label_y[id(r)]), textcoords="data",
                    ha="left" if x >= 0 else "right",
                    va="center", fontsize=8, color="#222222",
                    arrowprops=dict(arrowstyle="-", lw=0.55, color="#888888"))

    ax.set_xlabel("Variant-frequency difference\n(regimes containing heat − constant 30 °C; percentage points)")
    ax.set_ylabel("Statistical confidence  (−log₁₀ q)")
    ax.set_title("New-mutation candidates only")
    ax.legend(frameon=False, fontsize=8, loc="best")
    _floating_axes(ax)
    fig.tight_layout()
    fig.savefig(out_path, dpi=300, bbox_inches="tight", facecolor="white")
    plt.close(fig)


