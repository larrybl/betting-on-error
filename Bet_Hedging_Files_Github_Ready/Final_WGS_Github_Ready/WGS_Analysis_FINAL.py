def _odds(p):
    """Convert a fraction in (0, 1) to odds."""
    if not np.isfinite(p) or p <= 0.0 or p >= 1.0:
        return float("nan")
    return p / (1.0 - p)


def marker_odds_calibration_multiplier(day0_marker_read_fraction):
    """Calibrate KanMX/(KanMX + intact-HO) against the confirmed day-0 mixture.

    The two marker contigs need not yield equal read depth per cell.  The confirmed
    50:50 day-0 mixture therefore provides an empirical calibration anchor.  If the
    raw marker-read fraction in that sample is m0 and the known marked-cell fraction
    is p0, the correction is applied on the odds scale:

        corrected_odds = observed_odds * odds(p0) / odds(m0)

    This makes the day-0 sample recover its known composition without altering the
    ordering of later marker measurements.
    """
    p0 = DAY0_COMPETITION_PCT / 100.0
    observed_odds = _odds(day0_marker_read_fraction)
    target_odds = _odds(p0)
    if not np.isfinite(observed_odds) or not np.isfinite(target_odds):
        raise RuntimeError(
            "Cannot calibrate marker reads: day-0 marker fraction or configured "
            "day-0 composition is not strictly between 0 and 1."
        )
    return target_odds / observed_odds


def calibrate_marked_fraction(marker_read_fraction, odds_multiplier):
    """Convert the raw marker-read fraction to an estimated marked-cell fraction."""
    if marker_read_fraction != marker_read_fraction:  # NaN
        return float("nan")
    if marker_read_fraction <= 0.0:
        return 0.0
    if marker_read_fraction >= 1.0:
        return 1.0
    observed_odds = marker_read_fraction / (1.0 - marker_read_fraction)
    corrected_odds = observed_odds * odds_multiplier
    return corrected_odds / (1.0 + corrected_odds)


def edited_fraction(regime, calibrated_marked_fraction):
    """Convert calibrated marked-cell fraction into edited-strain fraction,
    using which genotype carries KanMX in that condition."""
    if calibrated_marked_fraction != calibrated_marked_fraction:  # NaN
        return float("nan")
    if regime in KANMX_MARKS_WT_IN:
        return 1.0 - calibrated_marked_fraction
    return calibrated_marked_fraction


